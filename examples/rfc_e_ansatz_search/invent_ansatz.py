#!/usr/bin/env python3
"""RFC-E MVP: deterministic sketch search + emit (oracle hook shaped for future AD)."""
from __future__ import annotations
import argparse, hashlib, json, itertools, sys
from pathlib import Path

LIBRARY = ["I", "Rx", "Ry", "Rz", "H", "CX"]

def sketches(seed: int, limit: int = 16):
    """Deterministic ordered slice of 2-gate product sketches, rotated by seed."""
    all_sk = list(itertools.product(LIBRARY, LIBRARY))  # 36
    start = seed % len(all_sk)
    rotated = all_sk[start:] + all_sk[:start]
    return rotated[: min(limit, len(rotated))]

def oracle(sketch, seed: int) -> float:
    # Placeholder classical surrogate — replace with Moonlab H2 / AD later.
    h = hashlib.sha256(f"{seed}:{sketch}".encode()).hexdigest()
    return int(h[:8], 16) / 0xFFFFFFFF

def emit_esk(sketch, score: float, seed: int) -> str:
    a, b = sketch
    return (
        f"; Generated by RFC-E invent_ansatz.py — seed={seed} score={score:.6f}\n"
        f"; STRETCH: replace oracle with Eshkol (derivative ...) / Moonlab H2 energy.\n"
        f"(define (invented-ansatz theta)\n"
        f"  ;; sketch: {a} then {b} on a 1-parameter toy\n"
        f"  (list '{a} '{b} theta))\n"
    )

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--out", type=Path, default=Path("generated_ansatz.esk"))
    args = ap.parse_args()
    cands = sketches(args.seed)
    ranked = sorted(((oracle(s, args.seed), s) for s in cands), key=lambda t: t[0])
    best_score, best = ranked[0]
    args.out.write_text(emit_esk(best, best_score, args.seed))
    print(json.dumps({"seed": args.seed, "winner": list(best), "score": best_score, "n": len(cands)}, sort_keys=True))
    return 0

if __name__ == "__main__":
    sys.exit(main())
